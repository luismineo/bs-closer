#!/usr/bin/env node
/**
 * Vendors DuckDuckGo's autoconsent library (MPL-2.0) into vendor/autoconsent/.
 *
 *   node scripts/update-autoconsent.mjs            # the pinned version below
 *   node scripts/update-autoconsent.mjs 16.50.0    # a specific version
 *
 * Needs node, npm and tar on PATH (tar ships with Windows 10+ and Git Bash).
 * The extension itself has no build step: this script only rewraps files from
 * the published npm package so they can be loaded as classic content scripts.
 *
 * Output:
 *   autoconsent.js     the library (CommonJS bundle), exposed to the isolated
 *                      world as globalThis.BSCloserAutoconsent
 *   rules.js           DuckDuckGo's compact CMP rule set, exposed as
 *                      globalThis.BSCloserAutoconsentRules
 *   eval-bridge.js     MAIN-world script holding the library's fixed "eval
 *                      snippets"; it runs one by id when content.js asks
 *   LICENSE            MPL-2.0 text from the package
 */
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const PINNED_VERSION = '16.43.2';
const PACKAGE = '@duckduckgo/autoconsent';

const version = process.argv[2] || PINNED_VERSION;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'vendor', 'autoconsent');
const work = mkdtempSync(join(tmpdir(), 'bs-closer-autoconsent-'));

const run = (cmd, args) => execFileSync(cmd, args, { cwd: work, encoding: 'utf8', shell: process.platform === 'win32' }).trim();

try {
  console.log(`Fetching ${PACKAGE}@${version}…`);
  const tarball = run('npm', ['pack', `${PACKAGE}@${version}`, '--silent']).split(/\r?\n/).pop();
  run('tar', ['-xzf', tarball]);
  const pkg = join(work, 'package');

  const header = (what) => [
    `/* ${what}`,
    ` * From ${PACKAGE}@${version} by DuckDuckGo — https://github.com/duckduckgo/autoconsent`,
    ' * Licensed under the Mozilla Public License 2.0 (see LICENSE in this folder).',
    ' * Generated by scripts/update-autoconsent.mjs — do not edit by hand. */',
  ].join('\n');

  // 1. Library: wrap the CommonJS bundle so it runs as a classic content script.
  const lib = readFileSync(join(pkg, 'dist', 'autoconsent.cjs.js'), 'utf8');
  if (/\brequire\(/.test(lib)) throw new Error('autoconsent.cjs.js now requires other modules; the wrapper needs updating.');
  writeFileSync(join(outDir, 'autoconsent.js'), [
    header('DuckDuckGo autoconsent library (isolated world).'),
    '(() => {',
    'const module = { exports: {} };',
    'const exports = module.exports;',
    lib,
    'globalThis.BSCloserAutoconsent = module.exports;',
    '})();',
    '',
  ].join('\n'));

  // 2. Rules: the compact rule set as a global (content scripts can't import JSON).
  const rules = JSON.parse(readFileSync(join(pkg, 'rules', 'compact-rules.json'), 'utf8'));
  writeFileSync(join(outDir, 'rules.js'), [
    header('DuckDuckGo autoconsent compact rule set.'),
    `globalThis.BSCloserAutoconsentRules = ${JSON.stringify(rules)};`,
    '',
  ].join('\n'));

  // 3. Eval bridge: the library's eval snippets are self-contained functions (the
  //    library itself ships them as source to a background script), so their
  //    source is copied into a MAIN-world script that runs them by id only.
  const { evalSnippets } = createRequire(import.meta.url)(join(pkg, 'dist', 'autoconsent.cjs.js'));
  const snippetEntries = Object.entries(evalSnippets)
    .map(([id, fn]) => `    ${JSON.stringify(id)}: ${fn.toString()},`)
    .join('\n');
  writeFileSync(join(outDir, 'eval-bridge.js'), [
    header('Eval bridge (MAIN world).'),
    '// Some autoconsent rules must read page state (e.g. a CMP\'s JS API), which the',
    '// isolated world cannot see. content.js asks for a snippet by id through a DOM',
    '// event; only the fixed snippets below can run, never code sent by anyone.',
    '(() => {',
    '  const snippets = {',
    snippetEntries,
    '  };',
    "  document.addEventListener('bs-closer:autoconsent-eval', (e) => {",
    '    let request;',
    "    try { request = JSON.parse(e.detail); } catch { return; }",
    '    const snippet = Object.prototype.hasOwnProperty.call(snippets, request.snippetId) ? snippets[request.snippetId] : null;',
    '    let result = false;',
    '    try { result = !!(snippet && snippet.call(window)); } catch { /* treated as false */ }',
    "    document.dispatchEvent(new CustomEvent('bs-closer:autoconsent-eval-result', {",
    '      detail: JSON.stringify({ id: request.id, result }),',
    '    }));',
    '  });',
    '})();',
    '',
  ].join('\n'));

  copyFileSync(join(pkg, 'LICENSE'), join(outDir, 'LICENSE'));
  console.log(`Vendored ${PACKAGE}@${version}: ${rules.r.length} declarative rules, ${Object.keys(evalSnippets).length} eval snippets.`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
